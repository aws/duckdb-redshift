#!/usr/bin/env bash
# Tool tests for third_party/redshift_odbc/tools/lib/driver_info.py, which fetch-driver.sh runs last
# with the lock it read through check-lock.sh. Each case runs check-lock.sh and driver_info.py as
# fetch-driver.sh does, on a copy of the tools and policy files, with a test lock over a small
# synthetic driver set, and checks the exit status, the message and the header. Run by
# run-tool-tests.sh.
set -euo pipefail

here="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
repo_odbc="$here/../../../third_party/redshift_odbc"
tmp="$(mktemp -d)"
trap 'rm -rf -- "${tmp:?}"' EXIT
# The header names each file by its real path, so the expected one is built from the real path too:
# a TMPDIR under a symbolic link (macOS's /var/folders is under /private) must not change it.
tmp="$(cd "$tmp" && pwd -P)"

n=0; failed=0
pass() { n=$((n+1)); echo "ok $n - $1"; }
fail() { n=$((n+1)); echo "not ok $n - $1"; failed=$((failed+1)); }
sha() { python3 -I -c 'import hashlib,sys; print(hashlib.sha256(open(sys.argv[1],"rb").read()).hexdigest())' "$1"; }

# tree <name>: a copy of the tools and policy files, so a case can change a policy file without
# touching the repository's. Prints its tools directory. Its environment lists are fixed test
# lists, so the expected header does not change when a policy file reclassifies a name.
tree() {
  local d="$tmp/$1/third_party/redshift_odbc" n
  mkdir -p "$d"; cp -R "$repo_odbc/tools" "$repo_odbc/policy" "$d/"
  for n in PGGSSLIB PGHOSTADDR PGKRBSRVNAME PGOPTIONS PGREQUIRESSL PGSERVICE PGSERVICEFILE PGSSLCERT \
    PGSSLCRL PGSSLKEY PGSSLROOTCERT PGSYSCONFDIR SSLKEYLOGFILE SSL_CERT_DIR KRB5_CONFIG KRB5_TRACE \
    KRB5CCNAME KRB5_KTNAME AWS_ENDPOINT_URL ODBCINI; do echo "$n  load"; done > "$d/policy/refused-environment.txt"
  echo "SSL_CERT_FILE  CaFile" > "$d/policy/known-environment.txt"
  echo "$d/tools"
}
# set_dir <name>: a driver set whose bytes the test lock below names. Prints its directory.
set_dir() {
  local d="$tmp/$1-set"; mkdir -p "$d"
  printf 'driver bytes\n' > "$d/librsodbc64.so"; printf 'licence\n' > "$d/LICENSE"
  printf 'notice\n' > "$d/NOTICE"; printf 'third party\n' > "$d/THIRD_PARTY_LICENSES"
  echo "$d"
}
ref="$(set_dir ref)"
hd="$(sha "$ref/librsodbc64.so")"; hl="$(sha "$ref/LICENSE")"; hn="$(sha "$ref/NOTICE")"; ht="$(sha "$ref/THIRD_PARTY_LICENSES")"
pkg="$(printf 'e%.0s' {1..64})"
url="https://s3.amazonaws.com/redshift-downloads/drivers/odbc/2.3.0.0/AmazonRedshiftODBC-64-bit-2.3.0.0.x86_64.rpm"
src="https://raw.githubusercontent.com/aws/amazon-redshift-odbc-driver/v2.3.0"
N1="*  notice  LICENSE  $hl  $src/LICENSE"; N2="*  notice  NOTICE  $hn  $src/NOTICE"
N3="*  notice  THIRD_PARTY_LICENSES  $ht  $src/THIRD_PARTY_LICENSES"
D="linux_amd64  driver  librsodbc64.so  $hd  $url  $pkg  ./opt/amazon/redshiftodbcx64/librsodbc64.so"
mk() {  # mk <name> <version-line> <status-line> <row>...; prints the lock's path
  printf '%s\n' "format 1" "$2" "$3" "${@:4}" > "$tmp/$1.lock"; echo "$tmp/$1.lock"
}
lock="$(mk good "version 2.3.0.0" "status development" "$D" "$N1" "$N2" "$N3")"

# shellcheck source=bounded.sh
source "$here/bounded.sh" # bounded <command>...: at most 20 seconds, its process group stopped
# run <tools> <lock> <platform> <set-dir>: check-lock.sh's output on <lock> into driver_info.py, as
# fetch-driver.sh pipes it, within 20 seconds; sets out and status.
run() {
  out="$( (bash "$1/check-lock.sh" "$2" | bounded python3 -I "$1/lib/driver_info.py" "$3" "$4" "$1/../policy") 2>&1)" &&
    status=0 || status=$?
}
expect_fail() {  # expect_fail <name> <substring> <set-dir>; after run
  if [[ "$status" == 1 && "$out" == *"$2"* && ! -e "$3/driver_info.h" ]]; then pass "$1"; else
    fail "$1 (exit $status, header $([[ -e "$3/driver_info.h" ]] && echo present || echo absent); output: $out)"; fi
}

# The manifest is "<sha256>  <size>  <name>\n" per file, sorted by name.
manifest="$(printf '%s  %s  %s\n' "$hl" 8 LICENSE "$hn" 7 NOTICE "$ht" 12 THIRD_PARTY_LICENSES "$hd" 13 librsodbc64.so)"
set_sha="$(printf '%s\n' "$manifest" | python3 -I -c 'import hashlib,sys; print(hashlib.sha256(sys.stdin.buffer.read()).hexdigest())')"
# Written straight to a file: bash 4.4 to 5.1 join a backslash-newline in a here-document inside
# $(...), which would join the expected header's continuation lines.
cat > "$tmp/expected.h" <<EOF
/* Generated by third_party/redshift_odbc/tools/fetch-driver.sh from the driver lock and
   the policy files, for linux_amd64. Do not edit. Also read by the assembler, so it holds only
   preprocessor definitions and C comments. */
#pragma once
#define REDSHIFT_DRIVER_VERSION "2.3.0.0"
#define REDSHIFT_DRIVER_PLATFORM "linux_amd64"
#define REDSHIFT_DRIVER_DEVELOPMENT 1
#define REDSHIFT_DRIVER_SET_SHA256 "$set_sha"
/* X(name, size in bytes, SHA-256, assembler symbol stem): the driver, then the notices. */
#define REDSHIFT_DRIVER_FILES(X) \\
	X("librsodbc64.so", 13, "$hd", driver) \\
	X("LICENSE", 8, "$hl", notice_license) \\
	X("NOTICE", 7, "$hn", notice_notice) \\
	X("THIRD_PARTY_LICENSES", 12, "$ht", notice_third_party_licenses)
/* Every refused name, whatever its phase; then the load-phase ones the loader checks. */
#define REDSHIFT_DRIVER_REFUSED_ENVIRONMENT "PGGSSLIB", "PGHOSTADDR", "PGKRBSRVNAME", "PGOPTIONS", "PGREQUIRESSL", "PGSERVICE", "PGSERVICEFILE", "PGSSLCERT", "PGSSLCRL", "PGSSLKEY", "PGSSLROOTCERT", "PGSYSCONFDIR", "SSLKEYLOGFILE", "SSL_CERT_DIR", "KRB5_CONFIG", "KRB5_TRACE", "KRB5CCNAME", "KRB5_KTNAME", "AWS_ENDPOINT_URL", "ODBCINI"
#define REDSHIFT_DRIVER_LOAD_REFUSED_ENVIRONMENT "PGGSSLIB", "PGHOSTADDR", "PGKRBSRVNAME", "PGOPTIONS", "PGREQUIRESSL", "PGSERVICE", "PGSERVICEFILE", "PGSSLCERT", "PGSSLCRL", "PGSSLKEY", "PGSSLROOTCERT", "PGSYSCONFDIR", "SSLKEYLOGFILE", "SSL_CERT_DIR", "KRB5_CONFIG", "KRB5_TRACE", "KRB5CCNAME", "KRB5_KTNAME", "AWS_ENDPOINT_URL", "ODBCINI"
/* {variable, the connection-string keyword that overrides it} */
#define REDSHIFT_DRIVER_OVERRIDDEN_ENVIRONMENT {"SSL_CERT_FILE", "CaFile"}
#define REDSHIFT_DRIVER_HOST_PREREQUISITES "libkeyutils.so.1"
/* X(assembler symbol stem, the absolute path the assembler embeds the file from) */
#define REDSHIFT_DRIVER_EMBED_FILES(X) \\
	X(driver, "$ref/librsodbc64.so") \\
	X(notice_license, "$ref/LICENSE") \\
	X(notice_notice, "$ref/NOTICE") \\
	X(notice_third_party_licenses, "$ref/THIRD_PARTY_LICENSES")
EOF
tools="$(tree base)"
run "$tools" "$lock" linux_amd64 "$ref"
# Compared and shown in Python, as cmp or diff may be missing.
same_or_diff() { python3 -I -c 'import difflib,sys
a, b = (open(p).read().splitlines(True) for p in sys.argv[1:])
sys.stdout.writelines(difflib.unified_diff(a, b, *sys.argv[1:])); sys.exit(a != b)' "$1" "$2"; }
if [[ "$status" == 0 ]] && same_or_diff "$tmp/expected.h" "$ref/driver_info.h" > "$tmp/header.diff"; then
  pass "generates the expected header"; else
  fail "generates the expected header (exit $status; output: $out)"; cat "$tmp/header.diff"; fi

d="$(set_dir order)"
run "$tools" "$(mk order "version 2.3.0.0" "status development" "$N3" "$N1" "$D" "$N2")" linux_amd64 "$d"
if [[ "$status" == 0 ]] && grep -q "REDSHIFT_DRIVER_SET_SHA256 \"$set_sha\"" "$d/driver_info.h"; then
  pass "the set hash does not depend on the order of the lock's rows"; else fail "set hash order (exit $status; $out)"; fi

d="$(set_dir other-lock)"
run "$tools" "$(mk rel "version 2.3.0.1" "status release" "${D//2.3.0.0/2.3.0.1}" "$N1" "$N2" "$N3")" linux_amd64 "$d"
if [[ "$status" == 0 ]] && grep -q 'VERSION "2.3.0.1"' "$d/driver_info.h" && grep -q 'DEVELOPMENT 0' "$d/driver_info.h"; then
  pass "another lock's version and status reach the header"; else fail "another lock (exit $status; $out)"; fi

d="$(set_dir quote)"
run "$tools" "$(mk quote "version 2.3.0.0" "status development" "$D" "$N1" "$N2" "$N3" "*  notice  a\"b  $hn  $src/x")" linux_amd64 "$d"
expect_fail "a lock that fails check-lock.sh, with a quote in a notice name, gives no header" "is not check-lock.sh output" "$d"

d="$(set_dir tampered)"; printf 'other bytes\n' > "$d/NOTICE"
run "$tools" "$lock" linux_amd64 "$d"
expect_fail "a set file that differs from the lock fails, naming it and both hashes" "NOTICE: SHA-256 $(sha "$d/NOTICE"), the lock expects $hn" "$d"
d="$(set_dir missing)"; rm "$d/LICENSE"
run "$tools" "$lock" linux_amd64 "$d"; expect_fail "a missing set file fails" "LICENSE: cannot open" "$d"
d="$(set_dir link)"; mv "$d/LICENSE" "$d/real"; ln -s real "$d/LICENSE"
run "$tools" "$lock" linux_amd64 "$d"; expect_fail "a set file that is a link fails" "not a link" "$d"
d="$(set_dir arm)"
run "$tools" "$lock" linux_arm64 "$d"; expect_fail "a platform with no driver row fails" "no driver row for linux_arm64" "$d"
run "$tools" "$lock" windows_arm64 "$d"; expect_fail "an unknown platform fails" "unknown platform" "$d"

# A FIFO at a locked name is refused, not waited on (run gives up after 20 seconds).
d="$(set_dir fifo)"; rm "$d/NOTICE"; mkfifo "$d/NOTICE"
run "$tools" "$lock" linux_amd64 "$d"
expect_fail "a FIFO at a locked name is refused without waiting" "NOTICE: not a regular file" "$d"

# The header names the files where the assembler reads them, links resolved and every byte that
# is not plainly safe escaped; the C compiler reads each path back as the real file.
real="$tmp/real dir é \"q\" \\b"; mkdir -p "$real"; ln -s "$real" "$tmp/via-link"
for f in librsodbc64.so LICENSE NOTICE THIRD_PARTY_LICENSES; do cp "$ref/$f" "$real/"; done
run "$tools" "$lock" linux_amd64 "$tmp/via-link"
if [[ "$status" == 0 ]] && grep -q 'X(notice_notice, ".*real\\040dir\\040\\303\\251\\040\\042q\\042\\040\\134b/NOTICE")' "$tmp/via-link/driver_info.h"; then
  pass "names each file by its real, escaped path"; else fail "escaped path (exit $status; $out)"; fi
if command -v cc >/dev/null; then
  printf '%s\n' '#include <stdio.h>' '#include "driver_info.h"' '#define OPEN(stem, path) if (!fopen(path, "rb")) return 1;' \
    'int main(void) { REDSHIFT_DRIVER_EMBED_FILES(OPEN) return 0; }' > "$tmp/open.c"
  if cc -I "$tmp/via-link" -o "$tmp/open" "$tmp/open.c" && "$tmp/open"; then pass "the compiler reads every escaped path back"
  else fail "the compiler reads every escaped path back"; fi
else echo "ok $((n += 1)) - the compiler reads every escaped path back # SKIP no cc"; fi

# The Windows resource script, from the checked-in template and a header the cases above wrote.
template="$here/../../../src/transport/driver/embedded_driver_pe.rc.in"
# resources <template> <header>; writes $tmp/out.rc, and sets out and status.
resources() {
  rm -f "$tmp/out.rc"
  out="$(python3 -I "$tools/lib/driver_info.py" resources "$1" "$2" "$tmp/out.rc" 2>&1)" && status=0 || status=$?
}
resources "$template" "$ref/driver_info.h"
{ grep -v '^@REDSHIFT_DRIVER_RESOURCES@$' "$template"
  printf 'DRIVER RCDATA "%s"\n' "$ref/librsodbc64.so"; printf 'NOTICE_LICENSE RCDATA "%s"\n' "$ref/LICENSE"
  printf 'NOTICE_NOTICE RCDATA "%s"\n' "$ref/NOTICE"
  printf 'NOTICE_THIRD_PARTY_LICENSES RCDATA "%s"\n' "$ref/THIRD_PARTY_LICENSES"; } > "$tmp/expected.rc"
if [[ "$status" == 0 ]] && grep -qx 'LANGUAGE 0, 0' "$template" && same_or_diff "$tmp/expected.rc" "$tmp/out.rc"; then
  pass "the resource script names each file of the header as RCDATA under its stem, in the neutral language"
else fail "the resource script (exit $status; $out; $(cat "$tmp/out.rc" 2>/dev/null))"; fi
printf '%s\n' '#define REDSHIFT_DRIVER_EMBED_FILES(X) \' '	X(driver, "C\072\134b\040d\134set\134rsodbc.dll")' > "$tmp/windows.h"
resources "$template" "$tmp/windows.h"
if [[ "$status" == 0 ]] && grep -qx 'DRIVER RCDATA "C:/b d/set/rsodbc.dll"' "$tmp/out.rc"; then
  pass "the resource script writes a Windows path with forward slashes"
else fail "Windows path in the resource script (exit $status; $out)"; fi
printf '%s\n' '#define REDSHIFT_DRIVER_EMBED_FILES(X) \' '	X(driver, "/b/\303\251/x")' > "$tmp/accent.h"
resources "$template" "$tmp/accent.h"
accent_rule='/b/\xc3\xa9/x: the resource compiler reads a path only in printable ASCII with no double quote; '
accent_rule+='build in a directory whose path is printable ASCII with no double quote'
if [[ "$status" == 1 && "$out" == *"$accent_rule" && ! -e "$tmp/out.rc" ]]; then
  pass "a build directory whose path is not ASCII is refused with its rule, and no script is written"
else fail "a path that is not ASCII (exit $status; $out)"; fi
printf '%s\n' '#define REDSHIFT_DRIVER_EMBED_FILES(X) \' '	X(driver, "/b/q\042/x")' > "$tmp/quote.h"
resources "$template" "$tmp/quote.h"
if [[ "$status" == 1 && "$out" == *'/b/q"/x: the resource compiler reads'* ]]; then pass "a path holding a double quote is refused"
else fail "a path holding a double quote (exit $status; $out)"; fi
printf 'LANGUAGE 0, 0\n' > "$tmp/no-line.rc.in"; printf '@REDSHIFT_DRIVER_RESOURCES@\n@REDSHIFT_DRIVER_RESOURCES@\n' > "$tmp/twice.rc.in"
no_line="$(resources "$tmp/no-line.rc.in" "$ref/driver_info.h"; echo "$status $out")"
twice="$(resources "$tmp/twice.rc.in" "$ref/driver_info.h"; echo "$status $out")"
resources "$template" "$tmp/expected.h.missing"
if [[ "$no_line" == "1 "*"has no line @REDSHIFT_DRIVER_RESOURCES@ alone"* && "$twice" == "1 "*"alone"* &&
  "$status" == 1 && "$out" == *"cannot read the template or the header"* ]]; then
  pass "a template without its one resource line, or a missing header, is refused"
else fail "template and header refusals ($no_line; $twice; $status $out)"; fi
sed '$d' "$ref/driver_info.h" > "$tmp/cut.h"
resources "$template" "$tmp/cut.h"
if [[ "$status" == 1 && "$out" == *"the header's embed list has no last row"* && ! -e "$tmp/out.rc" ]]; then
  pass "a header whose embed list is cut short is refused"
else fail "a header cut short (exit $status; $out)"; fi
printf '%s\n' '#define REDSHIFT_DRIVER_EMBED_FILES(X) \' '	X(driver, /b/x)' > "$tmp/unquoted.h"
resources "$template" "$tmp/unquoted.h"
if [[ "$status" == 1 && "$out" == *"has a row that is not X(stem, path): '\tX(driver, /b/x)'"* ]]; then
  pass "a header whose embed list has a row of another form is refused"
else fail "a row of another form (exit $status; $out)"; fi
printf '%s\n' '#define REDSHIFT_DRIVER_FILES(X) \' '	X("rsodbc.dll")' > "$tmp/no-list.h"
resources "$template" "$tmp/no-list.h"
if [[ "$status" == 1 && "$out" == *"the header has no embed list"* && ! -e "$tmp/out.rc" ]]; then
  pass "a readable header with no embed list is refused by its rule"
else fail "a header with no embed list (exit $status; $out)"; fi
printf '%s\n' '#define REDSHIFT_DRIVER_EMBED_FILES(X) \' '	X(driver, "/b/\011/x")' > "$tmp/tab.h"
resources "$template" "$tmp/tab.h"
if [[ "$status" == 1 && "$out" == *'the resource compiler reads a path only in printable ASCII'* && ! -e "$tmp/out.rc" ]]
then pass "a path holding a control byte is refused, and no script is written"
else fail "a path holding a control byte (exit $status; $out)"; fi
# The byte rule's edges: '~' (an 8.3 name such as RUNNER~1) is printable and passes, DEL is not.
printf '%s\n' '#define REDSHIFT_DRIVER_EMBED_FILES(X) \' '	X(driver, "C\072/RUNNER~1/x")' > "$tmp/tilde.h"
resources "$template" "$tmp/tilde.h"
if [[ "$status" == 0 ]] && grep -qx 'DRIVER RCDATA "C:/RUNNER~1/x"' "$tmp/out.rc"; then
  pass "a path holding '~', as an 8.3 name does, is written"
else fail "a path holding '~' (exit $status; $out)"; fi
printf '%s\n' '#define REDSHIFT_DRIVER_EMBED_FILES(X) \' '	X(driver, "/b/\177/x")' > "$tmp/del.h"
resources "$template" "$tmp/del.h"
if [[ "$status" == 1 && "$out" == *'the resource compiler reads a path only in printable ASCII'* && ! -e "$tmp/out.rc" ]]
then pass "a path holding DEL is refused"
else fail "a path holding DEL (exit $status; $out)"; fi
# The placeholder must be a line by itself; inside another line it is not one.
printf 'LANGUAGE 0, 0 // @REDSHIFT_DRIVER_RESOURCES@\n' > "$tmp/inline.rc.in"
resources "$tmp/inline.rc.in" "$ref/driver_info.h"
if [[ "$status" == 1 && "$out" == *"has no line @REDSHIFT_DRIVER_RESOURCES@ alone"* ]]; then
  pass "a template whose placeholder is inside another line is refused"
else fail "a placeholder inside a line (exit $status; $out)"; fi
printf '#define X "\303\251"\n' > "$tmp/utf8.h"
resources "$template" "$tmp/utf8.h"
if [[ "$status" == 1 && "$out" == *"cannot read the template or the header"* ]]; then
  pass "a header that is not ASCII is refused as unreadable, not with a traceback"
else fail "a header that is not ASCII (exit $status; $out)"; fi
out="$(python3 -I "$tools/lib/driver_info.py" resourcez "$template" "$ref/driver_info.h" "$tmp/out.rc" 2>&1)" &&
  status=0 || status=$?
if [[ "$status" == 2 && "$out" == *"usage: driver_info.py"* && ! -e "$tmp/out.rc" ]]; then
  pass "another verb with the resources verb's arguments is a usage error"
else fail "a misspelt verb (exit $status; $out)"; fi

# The macOS set lists no Linux prerequisite.
d="$(set_dir mac)"
run "$tools" "$(mk mac "version 2.3.0.0" "status development" "${D/linux_amd64/osx_arm64}" "$N1" "$N2" "$N3")" osx_arm64 "$d"
if [[ "$status" == 0 ]] && grep -qx '#define REDSHIFT_DRIVER_HOST_PREREQUISITES' "$d/driver_info.h"; then
  pass "a macOS header lists no Linux prerequisite"; else fail "macOS prerequisites (exit $status; $out)"; fi

# The checked-in policy files: the header's environment lists are exactly what they say.
real_tools="$tmp/real/third_party/redshift_odbc/tools"; mkdir -p "${real_tools%/tools}"
cp -R "$repo_odbc/tools" "$repo_odbc/policy" "${real_tools%/tools}/"
d="$(set_dir real)"; run "$real_tools" "$lock" linux_amd64 "$d"
pol="$repo_odbc/policy"
quoted() { awk '{ sub(/#.*/, "") } NF { printf "%s\"%s\"", (n++ ? ", " : ""), $1 }' "$1"; }
want_refused="$(quoted "$pol/refused-environment.txt")"
want_load="$(awk '{ sub(/#.*/, "") } NF && $2 == "load" { printf "%s\"%s\"", (n++ ? ", " : ""), $1 }' "$pol/refused-environment.txt")"
want_overridden="$(awk '{ sub(/#.*/, "") } NF == 2 && $2 != "-" { printf "%s{\"%s\", \"%s\"}", (n++ ? ", " : ""), $1, $2 }' "$pol/known-environment.txt")"
if [[ "$status" == 0 ]] && grep -qxF "#define REDSHIFT_DRIVER_REFUSED_ENVIRONMENT $want_refused" "$d/driver_info.h" &&
  grep -qxF "#define REDSHIFT_DRIVER_LOAD_REFUSED_ENVIRONMENT $want_load" "$d/driver_info.h" &&
  grep -qxF "#define REDSHIFT_DRIVER_OVERRIDDEN_ENVIRONMENT $want_overridden" "$d/driver_info.h"; then
  pass "the header's environment lists are the checked-in policy files' rows"
else fail "environment lists from the checked-in policy (exit $status; $out; $(grep ENVIRONMENT "$d/driver_info.h" 2>/dev/null))"; fi

# Policy files: the load-phase subset and the overridden list follow them.
tools="$(tree classified)"; policy="$tools/../policy"
sed -i.bak 's/^PGSERVICE  *load/PGSERVICE        connect/' "$policy/refused-environment.txt"
printf '%s\n' "PGHOST  Host" "PGPASSFILE  -  no password is used" "http_proxy  -  IAM goes through curl's own setting" \
  "PGCOMPRESSION  Compression" >> "$policy/known-environment.txt"
d="$(set_dir classified)"; run "$tools" "$lock" linux_amd64 "$d"
load_line="$(grep '^#define REDSHIFT_DRIVER_LOAD_REFUSED_ENVIRONMENT ' "$d/driver_info.h" || true)"
if [[ "$status" == 0 && "$load_line" == *'"PGSERVICEFILE"'* && "$load_line" != *'"PGSERVICE",'* ]] &&
  grep -qx '#define REDSHIFT_DRIVER_OVERRIDDEN_ENVIRONMENT {"SSL_CERT_FILE", "CaFile"}, {"PGHOST", "Host"}, {"PGCOMPRESSION", "Compression"}' "$d/driver_info.h" &&
  grep -q '"PGSERVICE", "PGSERVICEFILE"' "$d/driver_info.h"; then
  pass "the load subset and the overridden list follow the policy files; a - row is not compiled in"
else fail "policy lists (exit $status; $out)"; fi

# policy_case <name> <file> <line> <substring>: appends <line> to a copy's policy file; must fail.
policy_case() {
  local t; t="$(tree "$1")"; printf '%s\n' "$3" >> "$t/../policy/$2"
  local d; d="$(set_dir "$1")"; run "$t" "$lock" linux_amd64 "$d"; expect_fail "$1" "$4" "$d"
}
policy_case "refuses an unknown phase" refused-environment.txt "PGTZ  startup" "a row is <NAME> <load|handle|connect>"
policy_case "refuses a refused name that is not an identifier" refused-environment.txt "PG-TZ  load" "a row is <NAME> <load|handle|connect>"
policy_case "refuses a refused row with a third word" refused-environment.txt "PGTZ  load  extra" "a row is <NAME> <load|handle|connect>"
policy_case "refuses a known name that is not an identifier" known-environment.txt "PG-HOST  Host" "a row is <NAME> <Keyword>"
policy_case "refuses a keyword row with a third word" known-environment.txt "PGHOST  Host  extra" "the keyword must be one word"
policy_case "refuses a refused name listed twice" refused-environment.txt "PGOPTIONS  connect" "PGOPTIONS is listed twice"
policy_case "refuses a name in both lists" known-environment.txt "PGOPTIONS  Options" "PGOPTIONS is listed twice, or is in both lists"
policy_case "refuses a known row with neither keyword nor reason" known-environment.txt "PGHOST" "a row is <NAME> <Keyword>"
policy_case "refuses a - row without a reason" known-environment.txt "PGHOST  -" "a - row needs a reason"
policy_case "refuses a keyword with a quote" known-environment.txt 'PGHOST  Ho"st' "the keyword must be one word"
policy_case "refuses a prerequisite for an unknown system" host-prerequisites.txt "freebsd  libx.so" "a row is <linux|macos|windows>"
policy_case "refuses a prerequisite that is not a file name" host-prerequisites.txt "linux  lib/x.so" "a row is <linux|macos|windows>"
policy_case "refuses a prerequisite row with a third word" host-prerequisites.txt "linux  libx.so  extra" "a row is <linux|macos|windows>"
policy_case "refuses a Windows prerequisite row that carries a version" host-prerequisites.txt \
  "windows  VCRUNTIME140.dll  14.29.30139.0" "a windows row names the DLL only; its minimum file version is in the lock"

# The Windows set: the driver and its libraries from one MSI, a renamed file found under its
# embedded name, and the prerequisites, named in the policy and given their minimum versions by the
# lock.
wset="$tmp/windows-set"; mkdir -p "$wset"
printf 'driver dll\n' > "$wset/rsodbc.dll"; printf 'crypto dll\n' > "$wset/abcdefghijk23456.dll"
cp "$ref/LICENSE" "$ref/NOTICE" "$ref/THIRD_PARTY_LICENSES" "$wset/"
hw="$(sha "$wset/rsodbc.dll")"; hc="$(sha "$wset/abcdefghijk23456.dll")"
# The renamed set's hash, by the manifest's rule: the files are 11, 8, 7 and 12 bytes.
wset_sha="$(printf '%s  %s  %s\n' "$hl" 8 LICENSE "$hn" 7 NOTICE "$ht" 12 THIRD_PARTY_LICENSES \
  "$hc" 11 abcdefghijk23456.dll "$hw" 11 rsodbc.dll |
  python3 -I -c 'import hashlib,sys; print(hashlib.sha256(sys.stdin.buffer.read()).hexdigest())')"
lock_set_sha="$wset_sha"
msi="https://s3.amazonaws.com/redshift-downloads/drivers/odbc/2.3.0.0/AmazonRedshiftODBC64-2.3.0.0.msi"
wlock() {  # wlock <name> <prerequisite row>...: a format 2 lock of the Windows set; prints its path
  printf '%s\n' "format 2" "version 2.3.0.0" "status development" \
    "windows_amd64  driver  rsodbc.dll  $hw  $hw  $msi  $pkg  ./x/rsodbc.dll" \
    "windows_amd64  library  crypto.dll  $hc  $pkg  $msi  $pkg  ./x/crypto.dll" \
    "windows_amd64  rename  crypto.dll  abcdefghijk23456.dll" \
    "windows_amd64  patch  crypto.dll  0  aa  bb" "windows_amd64  name-seed  $pkg" \
    "windows_amd64  set-hash  $lock_set_sha" "${@:2}" "$N1" "$N2" "$N3" > "$tmp/$1.lock"
  echo "$tmp/$1.lock"
}
# The Windows rows, written here, so the case does not follow the checked-in list.
wtools="$(tree windows)"; printf '%s\n' "linux  libkeyutils.so.1" "windows  VCRUNTIME140.dll" \
  "windows  VCRUNTIME140_1.dll" > "$wtools/../policy/host-prerequisites.txt"
printf '%s\n' "# <file> <string>" "rsodbc.dll  Unable to initialize dbghelp.dll" \
  > "$wtools/../policy/windows/runtime-names.txt"
run "$wtools" "$(wlock wgood "windows_amd64  prerequisite  vcruntime140.dll  14.29.30139.0" \
  "windows_amd64  prerequisite  VCRUNTIME140_1.dll  14.29.0.0")" windows_amd64 "$wset"
if [[ "$status" == 0 ]] &&
  grep -qxF "	X(\"abcdefghijk23456.dll\", 11, \"$hc\", library_crypto_dll) \\" "$wset/driver_info.h" &&
  grep -qxF '#define REDSHIFT_DRIVER_HOST_PREREQUISITES "VCRUNTIME140.dll", "VCRUNTIME140_1.dll"' "$wset/driver_info.h" &&
  grep -qxF '#define REDSHIFT_DRIVER_PREREQUISITE_VERSIONS(X) X("vcruntime140.dll", 14, 29, 30139, 0) X("VCRUNTIME140_1.dll", 14, 29, 0, 0)' "$wset/driver_info.h" &&
  grep -qF "	X(library_crypto_dll, \"$wset/abcdefghijk23456.dll\")" "$wset/driver_info.h" &&
  grep -qxF '#define REDSHIFT_DRIVER_SYSTEM_DBGHELP 0' "$wset/driver_info.h" &&
  grep -qxF "#define REDSHIFT_DRIVER_SET_SHA256 \"$wset_sha\"" "$wset/driver_info.h" &&
  ! grep -q libkeyutils "$wset/driver_info.h"; then
  pass "writes the Windows file list under the embedded names, with each library's stem, and the prerequisites with their minimum versions"
else fail "the Windows header (exit $status; $out; $(cat "$wset/driver_info.h" 2>/dev/null))"; fi
rm -f "$wset/driver_info.h"
# The loader checks DbgHelp.dll only when a set file loads it by that bare name.
printf '%s\n' "rsodbc.dll  DbgHelp.dll  # rsodbc.dll's LoadLibrary" >> \
  "$wtools/../policy/windows/runtime-names.txt"
run "$wtools" "$(wlock wdbghelp "windows_amd64  prerequisite  vcruntime140.dll  14.29.30139.0" \
  "windows_amd64  prerequisite  VCRUNTIME140_1.dll  14.29.0.0")" windows_amd64 "$wset"
if [[ "$status" == 0 ]] && grep -qxF '#define REDSHIFT_DRIVER_SYSTEM_DBGHELP 1' \
  "$wset/driver_info.h"; then
  pass "a runtime-names.txt row of DbgHelp.dll turns the loader's DbgHelp.dll check on"
else fail \
  "a runtime-names.txt row of DbgHelp.dll turns the loader's DbgHelp.dll check on ($status; $out)"
fi
rm -f "$wset/driver_info.h"
# LoadLibrary adds .dll to a name without one, so a bare dbghelp is the same load.
printf '%s\n' "# <file> <string>" "rsodbc.dll  dbghelp" > "$wtools/../policy/windows/runtime-names.txt"
run "$wtools" "$(wlock wbare "windows_amd64  prerequisite  vcruntime140.dll  14.29.30139.0" \
  "windows_amd64  prerequisite  VCRUNTIME140_1.dll  14.29.0.0")" windows_amd64 "$wset"
if [[ "$status" == 0 ]] && grep -qxF '#define REDSHIFT_DRIVER_SYSTEM_DBGHELP 1' \
  "$wset/driver_info.h"; then
  pass "a bare dbghelp row turns the loader's DbgHelp.dll check on"
else fail "a bare dbghelp row turns the loader's DbgHelp.dll check on ($status; $out)"; fi
rm -f "$wset/driver_info.h"
run "$wtools" "$(wlock wmissing "windows_amd64  prerequisite  VCRUNTIME140.dll  14.29.30139.0")" windows_amd64 "$wset"
expect_fail "a Windows prerequisite without a minimum version in the lock fails" \
  "lists VCRUNTIME140_1.dll, whose minimum version the lock does not give" "$wset"
run "$wtools" "$(wlock wextra "windows_amd64  prerequisite  VCRUNTIME140.dll  14.29.30139.0" \
  "windows_amd64  prerequisite  VCRUNTIME140_1.dll  14.29.0.0" "windows_amd64  prerequisite  MSVCP140.dll  14.29.0.0")" windows_amd64 "$wset"
expect_fail "a minimum version for a DLL the policy does not list fails" \
  "the lock gives a minimum version for MSVCP140.dll, which policy/host-prerequisites.txt does not list" "$wset"
lock_set_sha="$hd"
run "$wtools" "$(wlock wsetsha "windows_amd64  prerequisite  VCRUNTIME140.dll  14.29.30139.0" \
  "windows_amd64  prerequisite  VCRUNTIME140_1.dll  14.29.0.0")" windows_amd64 "$wset"
expect_fail "a set-hash row the fetched set does not give fails" \
  "the set's manifest has SHA-256 $wset_sha, and the lock's set-hash is $hd" "$wset"
lock_set_sha="$wset_sha"
mv "$wset/abcdefghijk23456.dll" "$wset/crypto.dll"
run "$wtools" "$(wlock wname "windows_amd64  prerequisite  VCRUNTIME140.dll  14.29.30139.0" \
  "windows_amd64  prerequisite  VCRUNTIME140_1.dll  14.29.0.0")" windows_amd64 "$wset"
expect_fail "a renamed file under its MSI name fails" "abcdefghijk23456.dll: cannot open" "$wset"

# Without O_BINARY, Windows opens a set file in text mode, and the bytes hashed are not the file's.
# POSIX has no such flag, so the case gives os one and checks that file_facts passes it.
out="$(python3 -I - "$repo_odbc/tools/lib" "$ref" "$hl" <<'EOF' 2>&1
import os, sys
sys.dont_write_bytecode = True
sys.path.insert(0, sys.argv[1])
import driver_info
os.O_BINARY, real_open, flags = 0x40000000, os.open, []
os.open = lambda path, f, *rest: flags.append(f) or real_open(path, f & ~0x40000000, *rest)
errors = []
print(driver_info.file_facts(sys.argv[2], "LICENSE", sys.argv[3], errors), errors, flags[0] & 0x40000000 != 0)
EOF
)" || true
if [[ "$out" == "8 [] True" ]]; then pass "a set file is opened with O_BINARY where the platform has it"
else fail "a set file is opened with O_BINARY where the platform has it ($out)"; fi

# A header that cannot be renamed into place leaves no temporary behind: a directory stands in for
# driver_info.h.
d="$(set_dir rename)"; mkdir "$d/driver_info.h"
run "$tools" "$lock" linux_amd64 "$d"
if [[ "$status" == 1 && "$out" == *IsADirectoryError* ]] && ! compgen -G "$d/.driver_info.h.*" >/dev/null; then
  pass "a header that cannot be renamed into place leaves no temporary"
else fail "header temporary (exit $status; left: $(cd "$d" && echo .driver_info.h.*); $out)"; fi

echo "# $n cases, $((n - failed)) passed"
exit $(( failed > 0 ))
